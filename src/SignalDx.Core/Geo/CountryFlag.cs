/// <summary>
/// Country / territory identity for Band Activity transmitter flags.
/// UI prefers embedded PNG images (ISO code); emoji is a fallback only —
/// Windows often renders emoji flags as plain letters.
/// </summary>
public static class CountryFlag
{
    /// <summary>
    /// Flag emoji, optionally followed by a US/CA subdivision (e.g. "🇺🇸 IL").
    /// Prefer <see cref="ToIso"/> + PNG images in the UI.
    /// </summary>
    public static string From(string? country, string? state = null)
    {
        string? iso = ToIso(country, state);
        if (iso is null) return "";

        string flag = IsoToEmoji(iso);
        if (flag.Length == 0) return "";

        // Mainland USA / Canada: show subdivision after the national flag when we have it.
        if (!string.IsNullOrWhiteSpace(state) &&
            country is "USA" or "United States" or "Canada")
            return $"{flag} {state.Trim().ToUpperInvariant()}";

        return flag;
    }

    public static string IsoToEmoji(string? iso2)
    {
        if (string.IsNullOrWhiteSpace(iso2) || iso2.Length != 2)
            return "";
        char a = char.ToUpperInvariant(iso2[0]);
        char b = char.ToUpperInvariant(iso2[1]);
        if (a is < 'A' or > 'Z' || b is < 'A' or > 'Z')
            return "";
        return string.Concat(
            char.ConvertFromUtf32(a - 'A' + 0x1F1E6),
            char.ConvertFromUtf32(b - 'A' + 0x1F1E6));
    }

    /// <summary>Map CallsignCountry / UsState labels to ISO 3166-1 alpha-2.</summary>
    public static string? ToIso(string? country, string? state = null)
    {
        if (string.IsNullOrWhiteSpace(country))
            return null;

        // Territories often appear as Country from the prefix table.
        if (Aliases.TryGetValue(country.Trim(), out string? iso))
            return iso;

        return null;
    }

    /// <summary>
    /// Image key under Assets/Flags. Same as <see cref="ToIso"/> except Scotland, which has its own flag
    /// (ISO stays GB so Wanted country matching is unchanged).
    /// </summary>
    public static string? ToFlagImageKey(string? country, string? state = null)
    {
        if (string.Equals(country?.Trim(), "Scotland", StringComparison.OrdinalIgnoreCase))
            return "gb-sct";
        return ToIso(country, state);
    }

